#!/usr/bin/env node

// Starter family generator (docs/superpowers/specs/2026-11-03-starter-families-design.md
// §2): turns the per-family JSON sources under protocol/starters/ into the
// generated TypeScript module extension/starter-families.generated.ts and the
// `starter_types` line of protocol/capture-site/catalog.json, and checks every
// adapter's id template against the frozen protocol/starters/ids.lock.json.
// protocol/starters/README.md documents the family file shape.
//
// Usage: node scripts/generate-starters.mjs [--check] [--root <dir>]
//   (no flags)  write the generated files
//   --check     write nothing; print problems (one per line) and exit 1 if any
//   --root dir  repo root to read and write under (default: this repo)
//
// A family file that fails validation (an unknown field, or a missing
// required one) is reported the same way, file and field named, and stops
// generation before anything is written.

import { readFileSync, readdirSync, realpathSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parseArgs } from "node:util";

const REPO = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const STARTERS_DIR = "protocol/starters";
const LOCK_FILE = "protocol/starters/ids.lock.json";
const GENERATED_TS = "extension/starter-families.generated.ts";
const CATALOG_JSON = "protocol/capture-site/catalog.json";

const HEADER = "// Generated by scripts/generate-starters.mjs from protocol/starters/*.json. Do not edit.\n";

const INTERFACES = `
export type StarterScopeData =
  | { kind: "github_org" }
  | { kind: "tenant_name"; max: number; label: string; placeholder: string }
  | { kind: "unscoped"; notice: string };
export interface StarterTypeData {
  type: string; key: string; label: string;
  label_variants: { host_suffix: string; label: string }[];
  description: string;
  record_label: string | null;
  example_path: string | null;
  adapter: Record<string, unknown>;
  history: { match: Record<string, unknown>[] }[];
  status: { state: "certified" | "development"; method: "live" | "history" | null; checked_on: string | null; checked_by: string | null };
  docs: string;
}
export interface StarterFamilyData {
  family: StarterFamilyId;
  display_name: string;
  review_prompt: string | null;
  origin: { kind: "exact"; origin: string } | { kind: "subdomain"; suffix: string };
  scope: StarterScopeData | null;
  types: StarterTypeData[];
}
`;

const CATALOG_LINE_RE = /^ {2}"starter_types": \[.*\],$/m;

/** The dotted/bracketed field path a sub-object sits at, for error messages. */
function at(where, key) {
  return where ? `${where}.${key}` : key;
}

class FamilyValidationError extends Error {
  constructor(problems) {
    super(problems.join("\n"));
    this.problems = problems;
  }
}

function fail(problems, file, message) {
  problems.push(`${file}: ${message}`);
}

/** Every key of `obj` not in `allowed` is an "unknown field" problem. */
function checkKeys(problems, file, obj, allowed, where) {
  for (const key of Object.keys(obj)) {
    if (!allowed.includes(key)) fail(problems, file, `${where ? `${where} ` : ""}unknown field "${key}"`);
  }
}

/** Every key of `required` missing from `obj` is a "<path> is required" problem. */
function requireKeys(problems, file, obj, required, where) {
  for (const key of required) {
    if (!(key in obj)) fail(problems, file, `${at(where, key)} is required`);
  }
}

function isPlainObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

const ORIGIN_KEYS = { exact: ["kind", "origin"], subdomain: ["kind", "suffix"] };
const SCOPE_KEYS_BY_KIND = {
  github_org: ["kind"],
  tenant_name: ["kind", "max", "label", "placeholder"],
  unscoped: ["kind", "notice"],
};
const FAMILY_KEYS = ["family", "display_name", "review_prompt", "origin", "scope", "types"];
const TYPE_KEYS = [
  "type", "key", "label", "label_variants", "description", "record_label", "example_path",
  "adapter", "history", "status", "docs",
];
const ADAPTER_KEYS = ["type", "path_case", "match", "scope", "modes", "id", "title", "alias", "refs", "within", "unscoped"];
const ADAPTER_REQUIRED = ["type", "match", "id"];
const LABEL_VARIANT_KEYS = ["host_suffix", "label"];
const HISTORY_ENTRY_KEYS = ["match"];
const STATUS_KEYS = ["state", "method", "checked_on", "checked_by"];
const STATUS_STATES = ["certified", "development"];
const STATUS_METHODS = ["live", "history", null];

function validateOrigin(problems, file, origin, where) {
  if (!isPlainObject(origin)) {
    fail(problems, file, `${where} must be an object`);
    return;
  }
  const allowed = ORIGIN_KEYS[origin.kind];
  if (!allowed) {
    fail(problems, file, `${at(where, "kind")} must be "exact" or "subdomain"`);
    return;
  }
  checkKeys(problems, file, origin, allowed, where);
  requireKeys(problems, file, origin, allowed, where);
}

/** `scope`'s three kinds (protocol/starters/README.md "Scope kinds"):
 * `github_org` (today's GitHub organization scope, no extra fields),
 * `tenant_name` (a shared-origin tenant list: `max` names, 1-32, a field
 * `label` and a placeholder), and `unscoped` (no scope values at all; a
 * `notice` explains that every account in the profile is recorded). */
function validateScope(problems, file, scope, where) {
  if (scope === null) return;
  if (!isPlainObject(scope)) {
    fail(problems, file, `${where} must be null or an object`);
    return;
  }
  const allowed = SCOPE_KEYS_BY_KIND[scope.kind];
  if (!allowed) {
    fail(problems, file, `${at(where, "kind")} must be "github_org", "tenant_name" or "unscoped"`);
    return;
  }
  checkKeys(problems, file, scope, allowed, where);
  requireKeys(problems, file, scope, allowed, where);
  if (scope.kind === "tenant_name") {
    if ("max" in scope && !(Number.isInteger(scope.max) && scope.max >= 1 && scope.max <= 32)) {
      fail(problems, file, `${at(where, "max")} must be an integer from 1 to 32`);
    }
    if ("label" in scope && typeof scope.label !== "string") {
      fail(problems, file, `${at(where, "label")} must be a string`);
    }
    if ("placeholder" in scope && typeof scope.placeholder !== "string") {
      fail(problems, file, `${at(where, "placeholder")} must be a string`);
    }
  }
  if (scope.kind === "unscoped" && "notice" in scope && typeof scope.notice !== "string") {
    fail(problems, file, `${at(where, "notice")} must be a string`);
  }
}

/** Whether `value` contains a `{"$scope": true}` marker at any depth, the
 * placeholder `starterAdapter` (extension/starter-adapters.ts `withScope`)
 * replaces with the real scope values at runtime. */
function hasScopeMarker(value) {
  if (Array.isArray(value)) return value.some(hasScopeMarker);
  if (isPlainObject(value)) {
    const entries = Object.entries(value);
    if (entries.length === 1 && entries[0][0] === "$scope" && entries[0][1] === true) return true;
    return entries.some(([, entry]) => hasScopeMarker(entry));
  }
  return false;
}

/** Cross-checks a family's `scope` kind against how its types actually use
 * scope: a scoped family (`github_org` or `tenant_name`) needs a `$scope`
 * marker on every type's adapter; an unscoped family (`scope: null` or
 * `{kind: "unscoped"}`) must have neither a marker nor `{scope}` in an
 * `example_path`, and a `scope.kind === "unscoped"` family's adapters must
 * each carry the `unscoped: "acknowledged"` marker the engine requires for
 * SHARED_ORIGINS (protocol/starters/README.md). */
function validateScopeUse(problems, file, family) {
  if (!isPlainObject(family) || !Array.isArray(family.types)) return;
  const scopeKind = isPlainObject(family.scope) ? family.scope.kind : null;
  const scoped = scopeKind === "github_org" || scopeKind === "tenant_name";
  family.types.forEach((type, index) => {
    if (!isPlainObject(type) || !isPlainObject(type.adapter)) return;
    const where = `types[${index}]`;
    const marker = hasScopeMarker(type.adapter);
    if (scoped && !marker) {
      fail(problems, file, `${where}.adapter needs a {"$scope": true} marker for a scoped family`);
    }
    if (!scoped && marker) {
      fail(problems, file, `${where}.adapter has a {"$scope": true} marker but the family is unscoped`);
    }
    if (!scoped && typeof type.example_path === "string" && type.example_path.includes("{scope}")) {
      fail(problems, file, `${where}.example_path uses {scope} but the family has no scope values`);
    }
    if (scopeKind === "unscoped" && type.adapter.unscoped !== "acknowledged") {
      fail(problems, file, `${where}.adapter.unscoped must be "acknowledged" for an unscoped family`);
    }
  });
}

function validateAdapter(problems, file, adapter, where) {
  if (!isPlainObject(adapter)) {
    fail(problems, file, `${where} must be an object`);
    return;
  }
  checkKeys(problems, file, adapter, ADAPTER_KEYS, where);
  requireKeys(problems, file, adapter, ADAPTER_REQUIRED, where);
  if ("match" in adapter && (!Array.isArray(adapter.match) || adapter.match.length === 0)) {
    fail(problems, file, `${at(where, "match")} must be a non-empty array`);
  }
}

function validateLabelVariants(problems, file, variants, where) {
  if (!Array.isArray(variants)) {
    fail(problems, file, `${where} must be an array`);
    return;
  }
  variants.forEach((variant, index) => {
    const entryWhere = `${where}[${index}]`;
    if (!isPlainObject(variant)) {
      fail(problems, file, `${entryWhere} must be an object`);
      return;
    }
    checkKeys(problems, file, variant, LABEL_VARIANT_KEYS, entryWhere);
    requireKeys(problems, file, variant, LABEL_VARIANT_KEYS, entryWhere);
    if ("host_suffix" in variant && typeof variant.host_suffix !== "string") {
      fail(problems, file, `${at(entryWhere, "host_suffix")} must be a string`);
    }
    if ("label" in variant && typeof variant.label !== "string") {
      fail(problems, file, `${at(entryWhere, "label")} must be a string`);
    }
  });
}

function validateHistory(problems, file, history, where) {
  if (!Array.isArray(history)) {
    fail(problems, file, `${where} must be an array`);
    return;
  }
  history.forEach((entry, index) => {
    const entryWhere = `${where}[${index}]`;
    if (!isPlainObject(entry)) {
      fail(problems, file, `${entryWhere} must be an object`);
      return;
    }
    checkKeys(problems, file, entry, HISTORY_ENTRY_KEYS, entryWhere);
    requireKeys(problems, file, entry, HISTORY_ENTRY_KEYS, entryWhere);
    if ("match" in entry && !Array.isArray(entry.match)) {
      fail(problems, file, `${at(entryWhere, "match")} must be an array`);
    }
  });
}

function validateStatus(problems, file, status, where) {
  if (!isPlainObject(status)) {
    fail(problems, file, `${where} must be an object`);
    return;
  }
  checkKeys(problems, file, status, STATUS_KEYS, where);
  requireKeys(problems, file, status, STATUS_KEYS, where);
  if ("state" in status && !STATUS_STATES.includes(status.state)) {
    fail(problems, file, `${at(where, "state")} must be "certified" or "development"`);
  }
  if ("method" in status && !STATUS_METHODS.includes(status.method)) {
    fail(problems, file, `${at(where, "method")} must be "live", "history", or null`);
  }
  if ("checked_on" in status && status.checked_on !== null && typeof status.checked_on !== "string") {
    fail(problems, file, `${at(where, "checked_on")} must be a string or null`);
  }
  if ("checked_by" in status && status.checked_by !== null && typeof status.checked_by !== "string") {
    fail(problems, file, `${at(where, "checked_by")} must be a string or null`);
  }
}

function validateType(problems, file, type, where, originKind) {
  if (!isPlainObject(type)) {
    fail(problems, file, `${where} must be an object`);
    return;
  }
  checkKeys(problems, file, type, TYPE_KEYS, where);
  requireKeys(problems, file, type, TYPE_KEYS, where);
  if ("label_variants" in type) validateLabelVariants(problems, file, type.label_variants, at(where, "label_variants"));
  if ("adapter" in type) validateAdapter(problems, file, type.adapter, at(where, "adapter"));
  if ("history" in type) validateHistory(problems, file, type.history, at(where, "history"));
  if ("status" in type) validateStatus(problems, file, type.status, at(where, "status"));
  if ("type" in type && typeof type.type !== "string") fail(problems, file, `${at(where, "type")} must be a string`);
  if ("docs" in type && typeof type.docs !== "string") fail(problems, file, `${at(where, "docs")} must be a string`);
  if ("key" in type) {
    if (typeof type.key !== "string") fail(problems, file, `${at(where, "key")} must be a string`);
    else if (originKind === "subdomain" && !type.key.includes("{origin}")) {
      fail(problems, file, `${at(where, "key")} must contain "{origin}"`);
    }
  }
  if ("label" in type && typeof type.label !== "string") fail(problems, file, `${at(where, "label")} must be a string`);
  if ("description" in type && typeof type.description !== "string") fail(problems, file, `${at(where, "description")} must be a string`);
  if ("record_label" in type && type.record_label !== null && typeof type.record_label !== "string") {
    fail(problems, file, `${at(where, "record_label")} must be a string or null`);
  }
  if ("example_path" in type) {
    if (type.example_path !== null && typeof type.example_path !== "string") {
      fail(problems, file, `${at(where, "example_path")} must be a string or null`);
    } else if (typeof type.example_path === "string" && !type.example_path.startsWith("/")) {
      fail(problems, file, `${at(where, "example_path")} must start with "/"`);
    }
  }
}

function validateFamily(problems, file, family) {
  if (!isPlainObject(family)) {
    fail(problems, file, "must be an object");
    return;
  }
  checkKeys(problems, file, family, FAMILY_KEYS, "");
  requireKeys(problems, file, family, FAMILY_KEYS, "");
  if ("display_name" in family && typeof family.display_name !== "string") {
    fail(problems, file, "display_name must be a string");
  }
  if ("review_prompt" in family) {
    if (family.review_prompt !== null && typeof family.review_prompt !== "string") {
      fail(problems, file, "review_prompt must be a string or null");
    } else if (family.review_prompt === null) {
      const multiType = Array.isArray(family.types) && family.types.length > 1;
      const hasScope = "scope" in family && family.scope !== null;
      if (multiType || hasScope) {
        fail(problems, file, "review_prompt must be a string when a family has more than one type or a scope");
      }
    }
  }
  if ("origin" in family) validateOrigin(problems, file, family.origin, "origin");
  if ("scope" in family) validateScope(problems, file, family.scope, "scope");
  if ("types" in family) {
    if (!Array.isArray(family.types)) {
      fail(problems, file, "types must be an array");
    } else {
      const originKind = isPlainObject(family.origin) ? family.origin.kind : null;
      family.types.forEach((type, index) => validateType(problems, file, type, `types[${index}]`, originKind));
      validateScopeUse(problems, file, family);
    }
  }
}

/** Records `value` (a type's `type` or `key`) as declared in `file`, failing
 * if some earlier file already declared the same value: `STARTER_HISTORY`'s
 * `Object.fromEntries` in `extension/starter-adapters.ts` would silently
 * drop the earlier entry, the catalog's `starter_types` line would list a
 * duplicate `type` twice, and the second offer could never be matched via
 * its `key`. */
function checkDuplicate(problems, seen, kind, file, value) {
  const earlier = seen.get(value);
  if (earlier) fail(problems, file, `duplicate ${kind} "${value}" (also in ${earlier})`);
  else seen.set(value, file);
}

/** The validated `StarterFamilyData` objects under `<root>/protocol/starters`,
 * sorted by file name, each family's `types` kept in source order. Throws
 * `FamilyValidationError` (one problem line per issue) if any family file
 * fails validation. */
export function loadFamilies(root) {
  const dir = path.join(root, STARTERS_DIR);
  const files = readdirSync(dir)
    .filter((name) => name.endsWith(".json") && name !== "ids.lock.json")
    .sort();
  const problems = [];
  const families = [];
  const seenTypes = new Map();
  const seenKeys = new Map();
  for (const name of files) {
    const file = path.posix.join(STARTERS_DIR, name);
    let data;
    try {
      data = JSON.parse(readFileSync(path.join(dir, name), "utf8"));
    } catch (error) {
      fail(problems, file, `invalid JSON: ${error.message}`);
      continue;
    }
    validateFamily(problems, file, data);
    if (isPlainObject(data) && Array.isArray(data.types)) {
      for (const type of data.types) {
        if (!isPlainObject(type)) continue;
        if (typeof type.type === "string") checkDuplicate(problems, seenTypes, "type", file, type.type);
        if (typeof type.key === "string") checkDuplicate(problems, seenKeys, "key", file, type.key);
      }
    }
    families.push(data);
  }
  if (problems.length) throw new FamilyValidationError(problems);
  return families;
}

/** `families` ordered by the position, in `starterTypes`, of each family's
 * earliest type (plan "Open decisions" 4: UI family order is catalog
 * order). A family none of whose types appear in `starterTypes` sorts last,
 * stably, behind every family that does. */
function familyCatalogOrder(families, starterTypes) {
  const index = new Map(starterTypes.map((type, at) => [type, at]));
  return families
    .map((family, at) => ({
      family,
      at,
      rank: Math.min(...family.types.map((type) => index.get(type.type) ?? Number.POSITIVE_INFINITY)),
    }))
    .sort((a, b) => a.rank - b.rank || a.at - b.at)
    .map((entry) => entry.family.family);
}

/** The generated TypeScript module's full contents. Deterministic: `families`
 * is already sorted by file name, and each family's data is written exactly
 * as loaded, so re-running on the same sources reproduces the same file.
 * `starterTypes` is the catalog order (`catalogTypeOrder`); it defaults to
 * the families' own type order (their source order, concatenated in file
 * order), which is how PR A's single-argument `renderTs(families)` callers
 * still get a deterministic, if not catalog-ordered, result. */
export function renderTs(families, starterTypes) {
  const order = starterTypes ?? families.flatMap((family) => family.types.map((type) => type.type));
  const familyIds = familyCatalogOrder(families, order);
  const idsLine = `export const STARTER_FAMILY_IDS = [${familyIds.map((id) => JSON.stringify(id)).join(", ")}] as const; // catalog order\nexport type StarterFamilyId = (typeof STARTER_FAMILY_IDS)[number];\n`;
  return `${HEADER}\n${idsLine}${INTERFACES}\nexport const STARTER_FAMILIES: readonly StarterFamilyData[] = ${JSON.stringify(families, null, 2)};\n`;
}

/** The `starter_types` line's order: `current`'s order for every type still
 * present, then any new type (not in `current`) in family/source order. For
 * an unchanged type list this reproduces today's line exactly, so the
 * catalog's downstream (host, policy) readers see no change. Also the
 * catalog order `renderTs` uses for `STARTER_FAMILY_IDS` (main, below). */
export function catalogTypeOrder(families, current) {
  const types = families.flatMap((family) => family.types.map((type) => type.type));
  const known = new Set(types);
  const kept = current.filter((type) => known.has(type));
  const extra = types.filter((type) => !current.includes(type));
  return [...kept, ...extra];
}

/** The `starter_types` line of `protocol/capture-site/catalog.json`. */
export function renderCatalogLine(families, current) {
  const ordered = catalogTypeOrder(families, current);
  return `  "starter_types": [${ordered.map((type) => JSON.stringify(type)).join(", ")}],`;
}

/** Problems ("id template changed for <type>", "no lock entry for <type>")
 * from comparing each family type's `adapter.id` (and, for an adapter
 * declaring `within`, `<container type>#within`) against `lock`. Empty when
 * every id template matches its frozen entry (protocol/starters/README.md
 * "Frozen IDs"). */
export function checkLock(families, lock) {
  const problems = [];
  const check = (key, id) => {
    if (!(key in lock)) problems.push(`no lock entry for ${key}`);
    else if (lock[key] !== id) problems.push(`id template changed for ${key}`);
  };
  for (const family of families) {
    for (const type of family.types) {
      check(type.type, type.adapter.id);
      const within = type.adapter.within;
      if (isPlainObject(within) && typeof within.type === "string") {
        check(`${within.type}#within`, within.id);
      }
    }
  }
  return problems;
}

function main(argv) {
  const { values } = parseArgs({
    args: argv,
    options: {
      check: { type: "boolean", default: false },
      root: { type: "string" },
    },
  });
  const root = values.root ? path.resolve(values.root) : REPO;

  let families;
  try {
    families = loadFamilies(root);
  } catch (error) {
    if (!(error instanceof FamilyValidationError)) throw error;
    for (const problem of error.problems) console.log(problem);
    return 1;
  }

  const lock = JSON.parse(readFileSync(path.join(root, LOCK_FILE), "utf8"));
  const lockProblems = checkLock(families, lock);

  const catalogPath = path.join(root, CATALOG_JSON);
  const catalogSource = readFileSync(catalogPath, "utf8");
  const current = JSON.parse(catalogSource).starter_types;
  const catalogOrder = catalogTypeOrder(families, current);
  const catalogLine = `  "starter_types": [${catalogOrder.map((type) => JSON.stringify(type)).join(", ")}],`;
  const updatedCatalog = catalogSource.replace(CATALOG_LINE_RE, catalogLine);

  const ts = renderTs(families, catalogOrder);
  const tsPath = path.join(root, GENERATED_TS);

  if (values.check) {
    const problems = [...lockProblems];
    // Windows can still check this out as CRLF (.gitattributes `text eol=lf`
    // keeps the committed blob LF, but a worktree written by a test fixture,
    // or a checkout on a misconfigured client, may not match). renderTs
    // always writes LF, so normalise before comparing: --check should only
    // flag real drift, not line endings. (catalog.json's comparison already
    // tolerates CRLF: CATALOG_LINE_RE's `$` matches before `\r`, so the
    // matched region excludes the line ending and an unchanged line survives
    // the replace byte-for-byte.)
    const currentTs = (() => {
      try {
        return readFileSync(tsPath, "utf8").replace(/\r\n/g, "\n");
      } catch {
        return null;
      }
    })();
    if (currentTs !== ts) problems.push(`out of date: ${GENERATED_TS}`);
    if (updatedCatalog !== catalogSource) problems.push(`out of date: ${CATALOG_JSON}`);
    for (const problem of problems) console.log(problem);
    return problems.length ? 1 : 0;
  }

  if (lockProblems.length) {
    for (const problem of lockProblems) console.log(problem);
    return 1;
  }
  writeFileSync(tsPath, ts);
  if (updatedCatalog !== catalogSource) writeFileSync(catalogPath, updatedCatalog);
  return 0;
}

// Compare real paths: argv[1] may go through a symlink or contain characters
// a file URL escapes (spaces, Windows drive letters).
function isEntryPoint() {
  try {
    return import.meta.url === pathToFileURL(realpathSync(process.argv[1] ?? "")).href;
  } catch {
    return false;
  }
}

if (isEntryPoint()) {
  try {
    process.exit(main(process.argv.slice(2)));
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
