/** The dotted/bracketed field path a sub-object sits at, for error messages. */
function at(where, key) {
  return where ? `${where}.${key}` : key;
}

class FamilyValidationError extends Error {
  constructor(problems) {
    super(problems.join("\n"));
    this.problems = problems;
  }
}

function fail(problems, file, message) {
  problems.push(`${file}: ${message}`);
}

/** Every key of `obj` not in `allowed` is an "unknown field" problem. */
function checkKeys(problems, file, obj, allowed, where) {
  for (const key of Object.keys(obj)) {
    if (!allowed.includes(key)) fail(problems, file, `${where ? `${where} ` : ""}unknown field "${key}"`);
  }
}

/** Every key of `required` missing from `obj` is a "<path> is required" problem. */
function requireKeys(problems, file, obj, required, where) {
  for (const key of required) {
    if (!(key in obj)) fail(problems, file, `${at(where, key)} is required`);
  }
}

function isPlainObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** Whether `origin` (a canonical "https://host[:port]" origin string, no
 * path) is served by a family whose origin field is `familyOrigin`. Same
 * semantics as `starterFamily` in extension/starter-adapters.ts, applied to
 * one family's origin at a time rather than picking the best match across
 * every family: an exact origin is equal; a subdomain needs an `https:` URL
 * whose own `origin` equals the input (so `origin` is itself canonical), a
 * lower-cased hostname ending in `suffix`, and not the bare suffix host. */
export function familyClaims(familyOrigin, origin) {
  if (!isPlainObject(familyOrigin)) return false;
  if (familyOrigin.kind === "exact") return origin === familyOrigin.origin;
  if (familyOrigin.kind !== "subdomain") return false;
  let url;
  try {
    url = new URL(origin);
  } catch {
    return false;
  }
  if (url.origin !== origin || url.protocol !== "https:") return false;
  const host = url.hostname.toLowerCase();
  const suffix = familyOrigin.suffix;
  return host.endsWith(suffix) && host !== suffix.slice(1);
}

/** The canonical origin of `url`, or `null` when `url` is not a valid,
 * absolute URL. */
function originOf(url) {
  try {
    return new URL(url).origin;
  } catch {
    return null;
  }
}

const ORIGIN_KEYS = { exact: ["kind", "origin"], subdomain: ["kind", "suffix"] };
const SCOPE_KEYS_BY_KIND = {
  github_org: ["kind"],
  tenant_name: ["kind", "max", "label", "placeholder"],
  unscoped: ["kind", "notice"],
};
const FAMILY_KEYS = [
  "family", "display_name", "review_prompt", "origin", "scope",
  "sample_origin", "sample_scope", "overlaps", "types",
];
const TYPE_KEYS = [
  "type", "key", "label", "label_variants", "description", "record_label", "example_path",
  "adapter", "history", "status", "docs", "samples", "samples_shape", "vectors",
];
const ADAPTER_KEYS = ["type", "path_case", "match", "scope", "modes", "id", "title", "alias", "refs", "within", "unscoped"];
const ADAPTER_REQUIRED = ["type", "match", "id"];
const LABEL_VARIANT_KEYS = ["host_suffix", "label"];
const HISTORY_ENTRY_KEYS = ["match"];
const STATUS_KEYS = ["state", "method", "checked_on", "checked_by"];
const STATUS_STATES = ["certified", "development"];
const STATUS_METHODS = ["live", "history", null];
const SAMPLE_KEYS = ["url", "title", "shape", "note"];
const OVERLAP_KEYS = ["a", "b", "expect"];

function validateOrigin(problems, file, origin, where) {
  if (!isPlainObject(origin)) {
    fail(problems, file, `${where} must be an object`);
    return;
  }
  const allowed = ORIGIN_KEYS[origin.kind];
  if (!allowed) {
    fail(problems, file, `${at(where, "kind")} must be "exact" or "subdomain"`);
    return;
  }
  checkKeys(problems, file, origin, allowed, where);
  requireKeys(problems, file, origin, allowed, where);
}

/** `scope`'s three kinds (protocol/starters/README.md "Scope kinds"):
 * `github_org` (today's GitHub organization scope, no extra fields),
 * `tenant_name` (a shared-origin tenant list: `max` names, 1-32, a field
 * `label` and a placeholder), and `unscoped` (no scope values at all; a
 * `notice` explains that every account in the profile is recorded). */
function validateScope(problems, file, scope, where) {
  if (scope === null) return;
  if (!isPlainObject(scope)) {
    fail(problems, file, `${where} must be null or an object`);
    return;
  }
  const allowed = SCOPE_KEYS_BY_KIND[scope.kind];
  if (!allowed) {
    fail(problems, file, `${at(where, "kind")} must be "github_org", "tenant_name" or "unscoped"`);
    return;
  }
  checkKeys(problems, file, scope, allowed, where);
  requireKeys(problems, file, scope, allowed, where);
  if (scope.kind === "tenant_name") {
    if ("max" in scope && !(Number.isInteger(scope.max) && scope.max >= 1 && scope.max <= 32)) {
      fail(problems, file, `${at(where, "max")} must be an integer from 1 to 32`);
    }
    if ("label" in scope && typeof scope.label !== "string") {
      fail(problems, file, `${at(where, "label")} must be a string`);
    }
    if ("placeholder" in scope && typeof scope.placeholder !== "string") {
      fail(problems, file, `${at(where, "placeholder")} must be a string`);
    }
  }
  if (scope.kind === "unscoped" && "notice" in scope && typeof scope.notice !== "string") {
    fail(problems, file, `${at(where, "notice")} must be a string`);
  }
}

/** Whether `value` contains a `{"$scope": true}` marker at any depth, the
 * placeholder `starterAdapter` (extension/starter-adapters.ts `withScope`)
 * replaces with the real scope values at runtime. */
function hasScopeMarker(value) {
  if (Array.isArray(value)) return value.some(hasScopeMarker);
  if (isPlainObject(value)) {
    const entries = Object.entries(value);
    if (entries.length === 1 && entries[0][0] === "$scope" && entries[0][1] === true) return true;
    return entries.some(([, entry]) => hasScopeMarker(entry));
  }
  return false;
}

/** Cross-checks a family's `scope` kind against how its types actually use
 * scope: a scoped family (`github_org` or `tenant_name`) needs a `$scope`
 * marker on every type's adapter; an unscoped family (`scope: null` or
 * `{kind: "unscoped"}`) must have neither a marker nor `{scope}` in an
 * `example_path`, and a `scope.kind === "unscoped"` family's adapters must
 * each carry the `unscoped: "acknowledged"` marker the engine requires for
 * SHARED_ORIGINS (protocol/starters/README.md). */
function validateScopeUse(problems, file, family) {
  if (!isPlainObject(family) || !Array.isArray(family.types)) return;
  const scopeKind = isPlainObject(family.scope) ? family.scope.kind : null;
  const scoped = scopeKind === "github_org" || scopeKind === "tenant_name";
  family.types.forEach((type, index) => {
    if (!isPlainObject(type) || !isPlainObject(type.adapter)) return;
    const where = `types[${index}]`;
    const marker = hasScopeMarker(type.adapter);
    if (scoped && !marker) {
      fail(problems, file, `${where}.adapter needs a {"$scope": true} marker for a scoped family`);
    }
    if (!scoped && marker) {
      fail(problems, file, `${where}.adapter has a {"$scope": true} marker but the family is unscoped`);
    }
    if (!scoped && typeof type.example_path === "string" && type.example_path.includes("{scope}")) {
      fail(problems, file, `${where}.example_path uses {scope} but the family has no scope values`);
    }
    if (scopeKind === "unscoped" && type.adapter.unscoped !== "acknowledged") {
      fail(problems, file, `${where}.adapter.unscoped must be "acknowledged" for an unscoped family`);
    }
  });
}

function validateAdapter(problems, file, adapter, where) {
  if (!isPlainObject(adapter)) {
    fail(problems, file, `${where} must be an object`);
    return;
  }
  checkKeys(problems, file, adapter, ADAPTER_KEYS, where);
  requireKeys(problems, file, adapter, ADAPTER_REQUIRED, where);
  if ("match" in adapter && (!Array.isArray(adapter.match) || adapter.match.length === 0)) {
    fail(problems, file, `${at(where, "match")} must be a non-empty array`);
  }
}

function validateLabelVariants(problems, file, variants, where) {
  if (!Array.isArray(variants)) {
    fail(problems, file, `${where} must be an array`);
    return;
  }
  variants.forEach((variant, index) => {
    const entryWhere = `${where}[${index}]`;
    if (!isPlainObject(variant)) {
      fail(problems, file, `${entryWhere} must be an object`);
      return;
    }
    checkKeys(problems, file, variant, LABEL_VARIANT_KEYS, entryWhere);
    requireKeys(problems, file, variant, LABEL_VARIANT_KEYS, entryWhere);
    if ("host_suffix" in variant && typeof variant.host_suffix !== "string") {
      fail(problems, file, `${at(entryWhere, "host_suffix")} must be a string`);
    }
    if ("label" in variant && typeof variant.label !== "string") {
      fail(problems, file, `${at(entryWhere, "label")} must be a string`);
    }
  });
}

function validateHistory(problems, file, history, where) {
  if (!Array.isArray(history)) {
    fail(problems, file, `${where} must be an array`);
    return;
  }
  history.forEach((entry, index) => {
    const entryWhere = `${where}[${index}]`;
    if (!isPlainObject(entry)) {
      fail(problems, file, `${entryWhere} must be an object`);
      return;
    }
    checkKeys(problems, file, entry, HISTORY_ENTRY_KEYS, entryWhere);
    requireKeys(problems, file, entry, HISTORY_ENTRY_KEYS, entryWhere);
    if ("match" in entry && !Array.isArray(entry.match)) {
      fail(problems, file, `${at(entryWhere, "match")} must be an array`);
    }
  });
}

function validateStatus(problems, file, status, where) {
  if (!isPlainObject(status)) {
    fail(problems, file, `${where} must be an object`);
    return;
  }
  checkKeys(problems, file, status, STATUS_KEYS, where);
  requireKeys(problems, file, status, STATUS_KEYS, where);
  if ("state" in status && !STATUS_STATES.includes(status.state)) {
    fail(problems, file, `${at(where, "state")} must be "certified" or "development"`);
  }
  if ("method" in status && !STATUS_METHODS.includes(status.method)) {
    fail(problems, file, `${at(where, "method")} must be "live", "history", or null`);
  }
  if ("checked_on" in status && status.checked_on !== null && typeof status.checked_on !== "string") {
    fail(problems, file, `${at(where, "checked_on")} must be a string or null`);
  }
  if ("checked_by" in status && status.checked_by !== null && typeof status.checked_by !== "string") {
    fail(problems, file, `${at(where, "checked_by")} must be a string or null`);
  }
}

/** A type's `samples` array (recorded `{url, title, shape, note}` rows, one
 * per URL form `renderStarterShapes` carries into
 * `protocol/capture-site/starter-shapes.json`) and its `samples_shape`
 * switch. A sample's `url` must sit on the family's own `origin` (Review
 * Focus 1): a typo, a sibling family's host, or an excluded subdomain label
 * is caught here, file and field named, the same way an adapter's `match` is
 * never checked against a URL that could not reach it. `samples_shape` tells
 * `renderStarterShapes` whether this type contributes rows at all: a type
 * with no doc page worth citing (today: `github.repo`) is declared empty and
 * `false`, instead of silently contributing nothing. */
function validateSamples(problems, file, type, where, origin) {
  if ("samples_shape" in type && typeof type.samples_shape !== "boolean") {
    fail(problems, file, `${at(where, "samples_shape")} must be a boolean`);
  }
  if (!("samples" in type)) return;
  if (!Array.isArray(type.samples)) {
    fail(problems, file, `${at(where, "samples")} must be an array`);
    return;
  }
  type.samples.forEach((sample, index) => {
    const sampleWhere = `${at(where, "samples")}[${index}]`;
    if (!isPlainObject(sample)) {
      fail(problems, file, `${sampleWhere} must be an object`);
      return;
    }
    checkKeys(problems, file, sample, SAMPLE_KEYS, sampleWhere);
    requireKeys(problems, file, sample, SAMPLE_KEYS, sampleWhere);
    if ("url" in sample) {
      if (typeof sample.url !== "string") {
        fail(problems, file, `${at(sampleWhere, "url")} must be a string`);
      } else {
        const sampleOrigin = originOf(sample.url);
        if (sampleOrigin === null || !familyClaims(origin, sampleOrigin)) {
          fail(problems, file, `${at(sampleWhere, "url")} is not on this family's origin`);
        }
      }
    }
    if ("title" in sample && sample.title !== null && typeof sample.title !== "string") {
      fail(problems, file, `${at(sampleWhere, "title")} must be a string or null`);
    }
    if ("shape" in sample && typeof sample.shape !== "string") {
      fail(problems, file, `${at(sampleWhere, "shape")} must be a string`);
    }
    if ("note" in sample && typeof sample.note !== "string") {
      fail(problems, file, `${at(sampleWhere, "note")} must be a string`);
    }
  });
  if (type.samples_shape === false && type.samples.length > 0) {
    fail(problems, file, `${at(where, "samples")} must be empty when samples_shape is false`);
  }
  if (type.samples_shape === true && type.samples.length === 0) {
    fail(problems, file, `${at(where, "samples")} must not be empty when samples_shape is true`);
  }
}

/** A type's `vectors` (`protocol/adapter-templates/README.md`): each entry
 * is a `vectors.json` case for this type's synthesized `starter:<family>`
 * fixture, minus `doc` — `renderStarterVectors` adds `doc: {"$fixture":
 * "starter:<family>"}` itself, so a vector that already carries one is
 * refused rather than silently overwritten. A vector naming a `url` (an
 * `evaluate` case) must sit on the family's own `origin`, the same rule
 * `validateSamples` applies to recorded samples. Cross-file and
 * cross-vectors.json id duplicates are caught in `loadFamilies`, which
 * alone sees every family file and the legacy vectors file at once. */
function validateVectors(problems, file, type, where, origin) {
  if (!("vectors" in type)) return;
  if (!Array.isArray(type.vectors)) {
    fail(problems, file, `${at(where, "vectors")} must be an array`);
    return;
  }
  type.vectors.forEach((vector, index) => {
    const vectorWhere = `${at(where, "vectors")}[${index}]`;
    if (!isPlainObject(vector)) {
      fail(problems, file, `${vectorWhere} must be an object`);
      return;
    }
    if ("doc" in vector) {
      fail(problems, file, `${vectorWhere} must not carry "doc" (the family fixture is implied)`);
    }
    if ("url" in vector) {
      if (typeof vector.url !== "string") {
        fail(problems, file, `${at(vectorWhere, "url")} must be a string`);
      } else {
        const vectorOrigin = originOf(vector.url);
        if (vectorOrigin === null || !familyClaims(origin, vectorOrigin)) {
          fail(problems, file, `${at(vectorWhere, "url")} is not on this family's origin`);
        }
      }
    }
  });
}

function validateType(problems, file, type, where, origin) {
  if (!isPlainObject(type)) {
    fail(problems, file, `${where} must be an object`);
    return;
  }
  const originKind = isPlainObject(origin) ? origin.kind : null;
  checkKeys(problems, file, type, TYPE_KEYS, where);
  requireKeys(problems, file, type, TYPE_KEYS, where);
  if ("label_variants" in type) validateLabelVariants(problems, file, type.label_variants, at(where, "label_variants"));
  if ("adapter" in type) validateAdapter(problems, file, type.adapter, at(where, "adapter"));
  if ("history" in type) validateHistory(problems, file, type.history, at(where, "history"));
  if ("status" in type) validateStatus(problems, file, type.status, at(where, "status"));
  validateSamples(problems, file, type, where, origin);
  validateVectors(problems, file, type, where, origin);
  if ("type" in type && typeof type.type !== "string") fail(problems, file, `${at(where, "type")} must be a string`);
  if ("docs" in type && typeof type.docs !== "string") fail(problems, file, `${at(where, "docs")} must be a string`);
  if ("key" in type) {
    if (typeof type.key !== "string") fail(problems, file, `${at(where, "key")} must be a string`);
    else if (originKind === "subdomain" && !type.key.includes("{origin}")) {
      fail(problems, file, `${at(where, "key")} must contain "{origin}"`);
    }
  }
  if ("label" in type && typeof type.label !== "string") fail(problems, file, `${at(where, "label")} must be a string`);
  if ("description" in type && typeof type.description !== "string") fail(problems, file, `${at(where, "description")} must be a string`);
  if ("record_label" in type && type.record_label !== null && typeof type.record_label !== "string") {
    fail(problems, file, `${at(where, "record_label")} must be a string or null`);
  }
  if ("example_path" in type) {
    if (type.example_path !== null && typeof type.example_path !== "string") {
      fail(problems, file, `${at(where, "example_path")} must be a string or null`);
    } else if (typeof type.example_path === "string" && !type.example_path.startsWith("/")) {
      fail(problems, file, `${at(where, "example_path")} must start with "/"`);
    }
  }
}

/** `type`'s declared `within.type` target, or `null` when it declares none
 * (same reading as `extension/starter-adapters.ts` `withinTarget`,
 * duplicated here rather than imported so this script keeps no build-time
 * dependency on the TypeScript engine). */
function withinTarget(type) {
  const within = isPlainObject(type) ? type.adapter?.within : null;
  return isPlainObject(within) && typeof within.type === "string" ? within.type : null;
}

/** `family.sample_origin` (an origin `synthesizeFixture` and `main` use to
 * build the family's `starter:<family>` fixture) and `family.sample_scope`
 * (the scope values `{"$scope": true}` resolves to there). `sample_origin`
 * must sit on the family's own `origin`, the same rule a recorded sample's
 * `url` follows. `sample_scope` is non-empty exactly when the family's
 * `scope` kind needs account values (`github_org` or `tenant_name`); an
 * `unscoped` or `null` scope has none to give. */
function validateSampleScope(problems, file, family) {
  if ("sample_origin" in family) {
    if (typeof family.sample_origin !== "string") {
      fail(problems, file, "sample_origin must be a string");
    } else if (!familyClaims(family.origin, family.sample_origin)) {
      fail(problems, file, "sample_origin is not on this family's origin");
    }
  }
  if ("sample_scope" in family) {
    if (!Array.isArray(family.sample_scope) || family.sample_scope.some((value) => typeof value !== "string")) {
      fail(problems, file, "sample_scope must be an array of strings");
      return;
    }
    const scopeKind = isPlainObject(family.scope) ? family.scope.kind : null;
    const needsScope = scopeKind === "github_org" || scopeKind === "tenant_name";
    if (needsScope && family.sample_scope.length === 0) {
      fail(problems, file, "sample_scope must not be empty for a scoped family");
    }
    if (!needsScope && family.sample_scope.length > 0) {
      fail(problems, file, "sample_scope must be empty for an unscoped family");
    }
  }
}

/** `family.overlaps` (Open decision 3; spec §4 check 5): each entry names
 * two of the family's own types and declares the only permitted `expect`,
 * `"disjoint"`. Every unordered pair of the family's types that is not one
 * the other's `within` container (github.repo and the types that declare a
 * `within` naming it, for example) needs exactly one entry naming it, in
 * either order; a pair with no entry is reported `<a> and <b> have no
 * overlaps entry`, `<a>` and `<b>` in the family's own type order. */
function validateOverlaps(problems, file, family) {
  if (!("overlaps" in family)) return;
  if (!Array.isArray(family.overlaps)) {
    fail(problems, file, "overlaps must be an array");
    return;
  }
  const types = Array.isArray(family.types) ? family.types.filter(isPlainObject) : [];
  const typeNames = new Set(types.map((type) => type.type).filter((name) => typeof name === "string"));
  const declared = new Set();
  family.overlaps.forEach((entry, index) => {
    const where = `overlaps[${index}]`;
    if (!isPlainObject(entry)) {
      fail(problems, file, `${where} must be an object`);
      return;
    }
    checkKeys(problems, file, entry, OVERLAP_KEYS, where);
    requireKeys(problems, file, entry, OVERLAP_KEYS, where);
    if ("a" in entry) {
      if (typeof entry.a !== "string") fail(problems, file, `${at(where, "a")} must be a string`);
      else if (!typeNames.has(entry.a)) fail(problems, file, `${at(where, "a")} "${entry.a}" is not a type in this family`);
    }
    if ("b" in entry) {
      if (typeof entry.b !== "string") fail(problems, file, `${at(where, "b")} must be a string`);
      else if (!typeNames.has(entry.b)) fail(problems, file, `${at(where, "b")} "${entry.b}" is not a type in this family`);
    }
    if ("expect" in entry && entry.expect !== "disjoint") {
      fail(problems, file, `${at(where, "expect")} must be "disjoint"`);
    }
    if (typeof entry.a === "string" && typeof entry.b === "string") {
      declared.add(`${entry.a}\u0000${entry.b}`);
      declared.add(`${entry.b}\u0000${entry.a}`);
    }
  });
  for (let i = 0; i < types.length; i += 1) {
    for (let j = i + 1; j < types.length; j += 1) {
      const a = types[i];
      const b = types[j];
      if (typeof a.type !== "string" || typeof b.type !== "string") continue;
      if (withinTarget(a) === b.type || withinTarget(b) === a.type) continue;
      if (!declared.has(`${a.type}\u0000${b.type}`)) {
        fail(problems, file, `${a.type} and ${b.type} have no overlaps entry`);
      }
    }
  }
}

/** Validates one family object exactly as `loadFamilies` does for a family
 * file, appending a "<file>: <message>" problem per issue to `problems`.
 * Exported so a fixture that stands in for a family file in a test (for
 * example `extension/tests/starter-fixtures.mjs`) can be checked against
 * the same rules, instead of drifting from the file format unnoticed. */
export function validateFamily(problems, file, family) {
  if (!isPlainObject(family)) {
    fail(problems, file, "must be an object");
    return;
  }
  checkKeys(problems, file, family, FAMILY_KEYS, "");
  requireKeys(problems, file, family, FAMILY_KEYS, "");
  if ("display_name" in family && typeof family.display_name !== "string") {
    fail(problems, file, "display_name must be a string");
  }
  if ("review_prompt" in family) {
    if (family.review_prompt !== null && typeof family.review_prompt !== "string") {
      fail(problems, file, "review_prompt must be a string or null");
    } else if (family.review_prompt === null) {
      const multiType = Array.isArray(family.types) && family.types.length > 1;
      const hasScope = "scope" in family && family.scope !== null;
      if (multiType || hasScope) {
        fail(problems, file, "review_prompt must be a string when a family has more than one type or a scope");
      }
    }
  }
  if ("origin" in family) validateOrigin(problems, file, family.origin, "origin");
  if ("scope" in family) validateScope(problems, file, family.scope, "scope");
  if ("types" in family) {
    if (!Array.isArray(family.types)) {
      fail(problems, file, "types must be an array");
    } else {
      family.types.forEach((type, index) => validateType(problems, file, type, `types[${index}]`, family.origin));
      validateScopeUse(problems, file, family);
    }
  }
  validateSampleScope(problems, file, family);
  validateOverlaps(problems, file, family);
}

/** Records `value` (a type's `type` or `key`) as declared in `file`, failing
 * if some earlier file already declared the same value: `STARTER_HISTORY`'s
 * `Object.fromEntries` in `extension/starter-adapters.ts` would silently
 * drop the earlier entry, the catalog's `starter_types` line would list a
 * duplicate `type` twice, and the second offer could never be matched via
 * its `key`. */
function checkDuplicate(problems, seen, kind, file, value) {
  const earlier = seen.get(value);
  if (earlier) fail(problems, file, `duplicate ${kind} "${value}" (also in ${earlier})`);
  else seen.set(value, file);
}

/** The validated `StarterFamilyData` objects under `<root>/protocol/starters`,
 * sorted by file name, each family's `types` kept in source order. Throws
 * `FamilyValidationError` (one problem line per issue) if any family file
 * fails validation. */
export function loadFamilies(root) {
  const dir = path.join(root, STARTERS_DIR);
  const files = readdirSync(dir)
    .filter((name) => name.endsWith(".json") && name !== "ids.lock.json")
    .sort();
  const problems = [];
  const families = [];
  const seenTypes = new Map();
  const seenKeys = new Map();
  // Seeded with the legacy fixture's own case ids, so a family file's vector
  // reusing one of them is caught the same way a type or key collision with
  // an earlier family file is: `checkDuplicate` just sees an earlier "file"
  // that happens to be protocol/adapter-templates/vectors.json.
  const seenVectorIds = new Map();
  const legacyVectors = JSON.parse(readFileSync(path.join(root, VECTORS_JSON), "utf8"));
  for (const vectorCase of legacyVectors.cases ?? []) {
    if (isPlainObject(vectorCase) && typeof vectorCase.id === "string") {
      seenVectorIds.set(vectorCase.id, VECTORS_JSON);
    }
  }
  for (const name of files) {
    const file = path.posix.join(STARTERS_DIR, name);
    let data;
    try {
      data = JSON.parse(readFileSync(path.join(dir, name), "utf8"));
    } catch (error) {
      fail(problems, file, `invalid JSON: ${error.message}`);
      continue;
    }
    validateFamily(problems, file, data);
    if (isPlainObject(data) && Array.isArray(data.types)) {
      for (const type of data.types) {
        if (!isPlainObject(type)) continue;
        if (typeof type.type === "string") checkDuplicate(problems, seenTypes, "type", file, type.type);
        if (typeof type.key === "string") checkDuplicate(problems, seenKeys, "key", file, type.key);
        if (Array.isArray(type.vectors)) {
          for (const vector of type.vectors) {
            if (isPlainObject(vector) && typeof vector.id === "string") {
              checkDuplicate(problems, seenVectorIds, "vector id", file, vector.id);
            }
          }
        }
      }
    }
    families.push(data);
  }
  if (problems.length) throw new FamilyValidationError(problems);
  return families;
}

/** `families` ordered by the position, in `starterTypes`, of each family's
 * earliest type (plan "Open decisions" 4: UI family order is catalog
 * order). A family none of whose types appear in `starterTypes` sorts last,
 * stably, behind every family that does. */
function familyCatalogOrder(families, starterTypes) {
  const index = new Map(starterTypes.map((type, at) => [type, at]));
  return families
    .map((family, at) => ({
      family,
      at,
      rank: Math.min(...family.types.map((type) => index.get(type.type) ?? Number.POSITIVE_INFINITY)),
    }))
    .sort((a, b) => a.rank - b.rank || a.at - b.at)
    .map((entry) => entry.family.family);
}

/** Test-only type-level keys (Open decisions 4 and 10): recorded samples and
 * their shape-fixture switch live in the family file and in
 * `starter-shapes.json`, and a type's test vectors live in the family file
 * and in `starter-vectors.json`, not in the bundle the extension ships.
 * Dropping them keeps `STARTER_FAMILIES` byte-identical to before this
 * task. */
const TS_EXCLUDED_TYPE_KEYS = ["samples", "samples_shape", "vectors"];

/** Test-only family-level keys (Open decision 10): the sample origin and
 * scope `synthesizeFixture` uses, and the overlap declarations check 5
 * reads, live in the family file and in `starter-vectors.json`, not in the
 * bundle the extension ships. */
const TS_EXCLUDED_FAMILY_KEYS = ["sample_origin", "sample_scope", "overlaps"];

function omit(obj, keys) {
  const copy = { ...obj };
  for (const key of keys) delete copy[key];
  return copy;
}

/** The generated TypeScript module's full contents. Deterministic: `families`
 * is already sorted by file name, and each family's data is written exactly
 * as loaded (minus `TS_EXCLUDED_FAMILY_KEYS` and `TS_EXCLUDED_TYPE_KEYS`),
 * so re-running on the same sources reproduces the same file. `starterTypes`
 * is the catalog order (`catalogTypeOrder`); it defaults to the families'
 * own type order (their source order, concatenated in file order), which is
 * how PR A's single-argument `renderTs(families)` callers still get a
 * deterministic, if not catalog-ordered, result. */
export function renderTs(families, starterTypes) {
  const order = starterTypes ?? families.flatMap((family) => family.types.map((type) => type.type));
  const familyIds = familyCatalogOrder(families, order);
  const idsLine = `export const STARTER_FAMILY_IDS = [${familyIds.map((id) => JSON.stringify(id)).join(", ")}] as const; // catalog order\nexport type StarterFamilyId = (typeof STARTER_FAMILY_IDS)[number];\n`;
  const bundled = families.map((family) => ({
    ...omit(family, TS_EXCLUDED_FAMILY_KEYS),
    types: family.types.map((type) => omit(type, TS_EXCLUDED_TYPE_KEYS)),
  }));
  return `${HEADER}\n${idsLine}${INTERFACES}\nexport const STARTER_FAMILIES: readonly StarterFamilyData[] = ${JSON.stringify(bundled, null, 2)};\n`;
}

/** The JSON text (2-space indent, trailing newline) of
 * `protocol/capture-site/starter-shapes.json`: every sample recorded on a
 * type whose `samples_shape` is true, in catalog type order (`starterTypes`)
 * then sample order, each row's `note` suffixed with `(<type.docs>)` the
 * same way the 15 rows this file replaces named their doc page in
 * `shapes.json`. Same row shape as `shapes.json`, so the two files are
 * interchangeable fixture halves to every reader. */
export function renderStarterShapes(families, starterTypes) {
  const byType = new Map(families.flatMap((family) => family.types.map((type) => [type.type, type])));
  const types = starterTypes.filter((type) => byType.get(type)?.samples_shape === true);
  const accept = types.flatMap((type) => {
    const starterType = byType.get(type);
    return starterType.samples.map((sample) => ({
      note: `${sample.note} (${starterType.docs})`,
      url: sample.url,
      shape: sample.shape,
    }));
  });
  const body = {
    format: 1,
    generated: HEADER_SENTENCE,
    description: "Starter recorded samples (protocol/starters/*.json); same row format as shapes.json.",
    types,
    accept,
    reject: [],
  };
  return `${JSON.stringify(body, null, 2)}\n`;
}

/** `value` with every `{"$scope": true}` marker, at any depth, replaced by
 * `scope` (same reading as `extension/starter-adapters.ts` `withScope`,
 * duplicated here so this script keeps no build-time dependency on the
 * TypeScript engine). */
function withScope(value, scope) {
  if (Array.isArray(value)) return value.map((entry) => withScope(entry, scope));
  if (isPlainObject(value)) {
    const entries = Object.entries(value);
    if (entries.length === 1 && entries[0][0] === "$scope" && entries[0][1] === true) return [...scope];
    const copy = {};
    for (const [key, entry] of entries) copy[key] = withScope(entry, scope);
    return copy;
  }
  return value;
}

/** The document `synthesizeFixture` writes for `family`
 * (`protocol/adapter-templates/README.md`'s "adapter document" shape): one
 * artifact per type, in source order, each the same document
 * `starterOffers(family.sample_origin, family.sample_scope)` would build at
 * runtime for that origin — the template with `origin` inserted right
 * after `type`, and every `{"$scope": true}` marker resolved against
 * `family.sample_scope` (`extension/starter-adapters.ts` `starterAdapter`).
 * `extension/tests/starter-families.test.mjs` ("starter-vectors fixtures
 * are the runtime offers") pins the two together. */
export function synthesizeFixture(family) {
  const artifacts = family.types.map((type) => {
    const { type: adapterType, ...rest } = type.adapter;
    return { type: adapterType, origin: family.sample_origin, ...withScope(rest, family.sample_scope) };
  });
  return { format: 1, artifacts };
}

/** A type's own `vectors` entries (`protocol/starters/README.md`), each a
 * `vectors.json` case missing only `doc`, with `doc: {"$fixture":
 * "starter:<family>"}` inserted right after `impls` (the position every
 * hand-written vector uses) rather than merely appended. */
function withFixtureDoc(vector, fixtureName) {
  const { id, kind, why, impls, ...rest } = vector;
  return { id, kind, why, impls, doc: { "$fixture": fixtureName }, ...rest };
}

/** The JSON text of `protocol/adapter-templates/starter-vectors.json`: one
 * synthesized `starter:<family>` fixture per family (`synthesizeFixture`),
 * in catalog family order (`familyCatalogOrder`). Per family, the cases are
 * `validate.starter.<family>` (the fixture itself is a valid format-1
 * document), `overlap_report.starter.<family>` (the family's declared
 * `overlaps`, Open decision 3, are the whole set of pairs that may
 * overlap), then each type's own `vectors`, in source order, each pointed
 * at the family's fixture. */
export function renderStarterVectors(families, starterTypes) {
  const order = familyCatalogOrder(families, starterTypes);
  const byFamily = new Map(families.map((family) => [family.family, family]));
  const fixtures = {};
  const cases = [];
  for (const familyId of order) {
    const family = byFamily.get(familyId);
    const fixtureName = `starter:${familyId}`;
    fixtures[fixtureName] = synthesizeFixture(family);
    cases.push({
      id: `validate.starter.${familyId}`,
      kind: "validate",
      why: `generated: the synthesized ${fixtureName} fixture (${STARTERS_DIR}/${familyId}.json) is a valid format-1 document`,
      impls: ["rust", "ts"],
      doc: { "$fixture": fixtureName },
      expect: { ok: true },
    });
    cases.push({
      id: `overlap_report.starter.${familyId}`,
      kind: "overlap_report",
      why: `generated: ${familyId}'s declared overlaps (${STARTERS_DIR}/${familyId}.json) are the whole set of rule pairs that may overlap`,
      impls: ["rust"],
      doc: { "$fixture": fixtureName },
      expect: { pairs: [] },
    });
    for (const type of family.types) {
      for (const vector of type.vectors) cases.push(withFixtureDoc(vector, fixtureName));
    }
  }
  const body = { vectors_format: 1, generated: HEADER_SENTENCE, fixtures, cases };
  return `${JSON.stringify(body, null, 2)}\n`;
}

/** The `starter_types` line's order: `current`'s order for every type still
 * present, then any new type (not in `current`) in family/source order. For
 * an unchanged type list this reproduces today's line exactly, so the
 * catalog's downstream (host, policy) readers see no change. Also the
 * catalog order `renderTs` uses for `STARTER_FAMILY_IDS` (main, below). */
export function catalogTypeOrder(families, current) {
  const types = families.flatMap((family) => family.types.map((type) => type.type));
  const known = new Set(types);
  const kept = current.filter((type) => known.has(type));
  const extra = types.filter((type) => !current.includes(type));
  return [...kept, ...extra];
}

/** The `starter_types` line of `protocol/capture-site/catalog.json`. */
export function renderCatalogLine(families, current) {
  const ordered = catalogTypeOrder(families, current);
  return `  "starter_types": [${ordered.map((type) => JSON.stringify(type)).join(", ")}],`;
}

/** Problems ("id template changed for <type>", "no lock entry for <type>")
 * from comparing each family type's `adapter.id` (and, for an adapter
 * declaring `within`, `<container type>#within`) against `lock`. Empty when
 * every id template matches its frozen entry (protocol/starters/README.md
 * "Frozen IDs"). */
export function checkLock(families, lock) {
  const problems = [];
  const check = (key, id) => {
    if (!(key in lock)) problems.push(`no lock entry for ${key}`);
    else if (lock[key] !== id) problems.push(`id template changed for ${key}`);
  };
  for (const family of families) {
    for (const type of family.types) {
      check(type.type, type.adapter.id);
      const within = type.adapter.within;
      if (isPlainObject(within) && typeof within.type === "string") {
        check(`${within.type}#within`, within.id);
      }
    }
  }
  return problems;
}

function main(argv) {
  const { values } = parseArgs({
    args: argv,
    options: {
      check: { type: "boolean", default: false },
      root: { type: "string" },
    },
  });
  const root = values.root ? path.resolve(values.root) : REPO;

  let families;
  try {
    families = loadFamilies(root);
  } catch (error) {
    if (!(error instanceof FamilyValidationError)) throw error;
    for (const problem of error.problems) console.log(problem);
    return 1;
  }

  const lock = JSON.parse(readFileSync(path.join(root, LOCK_FILE), "utf8"));
  const lockProblems = checkLock(families, lock);

  const catalogPath = path.join(root, CATALOG_JSON);
  const catalogSource = readFileSync(catalogPath, "utf8");
  const current = JSON.parse(catalogSource).starter_types;
  const catalogOrder = catalogTypeOrder(families, current);
  const catalogLine = renderCatalogLine(families, current);
  const updatedCatalog = catalogSource.replace(CATALOG_LINE_RE, catalogLine);

  const ts = renderTs(families, catalogOrder);
  const tsPath = path.join(root, GENERATED_TS);

  const starterShapes = renderStarterShapes(families, catalogOrder);
  const starterShapesPath = path.join(root, STARTER_SHAPES);

  const starterVectors = renderStarterVectors(families, catalogOrder);
  const starterVectorsPath = path.join(root, STARTER_VECTORS);

  // Windows can still check this out as CRLF (.gitattributes `text eol=lf`
  // keeps the committed blob LF, but a worktree written by a test fixture,
  // or a checkout on a misconfigured client, may not match). renderTs and
  // renderStarterShapes always write LF, so normalise before comparing:
  // --check should only flag real drift, not line endings. (catalog.json's
  // comparison already tolerates CRLF: CATALOG_LINE_RE's `$` matches before
  // `\r`, so the matched region excludes the line ending and an unchanged
  // line survives the replace byte-for-byte.)
  const readNormalised = (candidatePath) => {
    try {
      return readFileSync(candidatePath, "utf8").replace(/\r\n/g, "\n");
    } catch {
      return null;
    }
  };

  if (values.check) {
    const problems = [...lockProblems];
    if (readNormalised(tsPath) !== ts) problems.push(`out of date: ${GENERATED_TS}`);
    if (updatedCatalog !== catalogSource) problems.push(`out of date: ${CATALOG_JSON}`);
    if (readNormalised(starterShapesPath) !== starterShapes) problems.push(`out of date: ${STARTER_SHAPES}`);
    if (readNormalised(starterVectorsPath) !== starterVectors) problems.push(`out of date: ${STARTER_VECTORS}`);
    for (const problem of problems) console.log(problem);
    return problems.length ? 1 : 0;
  }

  if (lockProblems.length) {
    for (const problem of lockProblems) console.log(problem);
    return 1;
  }
  writeFileSync(tsPath, ts);
  if (updatedCatalog !== catalogSource) writeFileSync(catalogPath, updatedCatalog);
  writeFileSync(starterShapesPath, starterShapes);
  writeFileSync(starterVectorsPath, starterVectors);
  return 0;
}

// Compare real paths: argv[1] may go through a symlink or contain characters
// a file URL escapes (spaces, Windows drive letters).
function isEntryPoint() {
  try {
    return import.meta.url === pathToFileURL(realpathSync(process.argv[1] ?? "")).href;
  } catch {
    return false;
  }
}

if (isEntryPoint()) {
  try {
    process.exit(main(process.argv.slice(2)));
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
