/** The dotted/bracketed field path a sub-object sits at, for error messages. */
function at(where, key) {
  return where ? `${where}.${key}` : key;
}

class FamilyValidationError extends Error {
  constructor(problems) {
    super(problems.join("\n"));
    this.problems = problems;
  }
}

function fail(problems, file, message) {
  problems.push(`${file}: ${message}`);
}

/** A type's `docs` is joined onto the root and read, and the README links
 * it by basename, so it must name a `.md` file directly inside
 * docs/adapters/ (brwr-p2a7). True only for `docs/adapters/<name>.md` with
 * no separator, backslash or leading dot in `<name>`, which also rules out
 * `..`, `.` and absolute paths; the normalized-path check is a second guard.
 * This checks the text only: `docsFileProblem` checks the file itself. */
function isContainedDocsPath(docs) {
  if (typeof docs !== "string" || !/^docs\/adapters\/[^/\\.][^/\\]*\.md$/.test(docs)) return false;
  return path.posix.dirname(path.posix.normalize(docs)) === DOCS_ADAPTERS_DIR;
}

const lstatOrNull = (file) => {
  try {
    return lstatSync(file);
  } catch {
    return null;
  }
};

/** Why `<root>/<docs>` must not be read, or null (#463 review I1): a
 * contained path can still name a symlink (a PR can commit one), or sit
 * under a docs/adapters that is one. Compares real paths, so neither a
 * symlinked folder nor a symlinked file leads outside root. A missing file
 * is null here: the caller reports it as missing. */
function docsFileProblem(root, docs) {
  const dir = path.join(root, DOCS_ADAPTERS_DIR);
  const dirStat = lstatOrNull(dir);
  if (dirStat === null) return null;
  if (dirStat.isSymbolicLink() || realpathSync(dir) !== path.join(realpathSync(root), DOCS_ADAPTERS_DIR)) {
    return `${DOCS_ADAPTERS_DIR} must not be a symlink`;
  }
  const file = path.join(root, docs);
  const stat = lstatOrNull(file);
  if (stat === null) return null;
  if (stat.isSymbolicLink()) return `${docs} must not be a symlink`;
  if (!stat.isFile() || path.dirname(realpathSync(file)) !== realpathSync(dir)) return `${docs} must be a file in ${DOCS_ADAPTERS_DIR}`;
  return null;
}

/** The generated outputs among `files` that are symlinks (#463 review I2):
 * write mode never writes through one, which could reach outside root. */
function symlinkedOutputs(root, files) {
  return files.filter((file) => lstatOrNull(file)?.isSymbolicLink()).map((file) => path.relative(root, file).split(path.sep).join("/"));
}

const DOCS_PATH_RULE = `must name a file ${DOCS_ADAPTERS_DIR}/<name>.md`;

/** Every key of `obj` not in `allowed` is an "unknown field" problem. */
function checkKeys(problems, file, obj, allowed, where) {
  for (const key of Object.keys(obj)) {
    if (!allowed.includes(key)) fail(problems, file, `${where ? `${where} ` : ""}unknown field "${key}"`);
  }
}

/** Every key of `required` missing from `obj` is a "<path> is required" problem. */
function requireKeys(problems, file, obj, required, where) {
  for (const key of required) {
    if (!(key in obj)) fail(problems, file, `${at(where, key)} is required`);
  }
}

function isPlainObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** Whether `origin` (a canonical "https://host[:port]" origin string, no
 * path) is served by a family whose origin field is `familyOrigin`. Same
 * semantics as `starterFamily` in extension/starter-adapters.ts, applied to
 * one family's origin at a time rather than picking the best match across
 * every family: an exact origin is equal; a subdomain needs an `https:` URL
 * whose own `origin` equals the input (so `origin` is itself canonical), a
 * lower-cased hostname ending in `suffix`, and not the bare suffix host.
 * Once that permissive match holds, a strict subdomain family (Task 4:
 * `labels` and/or `exclude`) narrows it further: take `prefix = host.slice(0,
 * -suffix.length)`, the labels between the host and the suffix. `labels: 1`
 * refuses a `prefix` with more than one label (a dot in it); `exclude`
 * refuses a `prefix` whose first label (its leftmost, nearest the host's
 * start) names one of the excluded product hosts (`www`, `signin`), or
 * starts with an excluded prefix (an entry ending in `*`, `fupload-*`;
 * `excludes`). A multi-origin family (`kind: "any"`) claims `origin` when
 * any one of its `of` members does. */
export function familyClaims(familyOrigin, origin) {
  if (!isPlainObject(familyOrigin)) return false;
  if (familyOrigin.kind === "any") {
    return Array.isArray(familyOrigin.of) && familyOrigin.of.some((member) => familyClaims(member, origin));
  }
  if (familyOrigin.kind === "exact") return origin === familyOrigin.origin;
  if (familyOrigin.kind !== "subdomain") return false;
  let url;
  try {
    url = new URL(origin);
  } catch {
    return false;
  }
  if (url.origin !== origin || url.protocol !== "https:") return false;
  const host = url.hostname.toLowerCase();
  const suffix = familyOrigin.suffix;
  if (!(host.endsWith(suffix) && host !== suffix.slice(1))) return false;
  const prefix = host.slice(0, -suffix.length);
  if (familyOrigin.labels && prefix.includes(".")) return false;
  if (familyOrigin.exclude && excludes(familyOrigin.exclude, prefix.split(".")[0])) return false;
  return true;
}

/** Whether a subdomain origin's `exclude` list refuses a host whose first
 * label is `label`: an entry is either a whole label (`www`, equal) or a
 * label prefix ending in a single `*` (`fupload-*`, `label` starts with
 * `fupload-`). Same rule as `excludes` in extension/starter-adapters.ts. */
export function excludes(exclude, label) {
  return exclude.some((entry) => (entry.endsWith("*") ? label.startsWith(entry.slice(0, -1)) : label === entry));
}

/** The single-kind origins a family's `origin` is made of: its `of` members
 * for a multi-origin (`kind: "any"`) family, otherwise just `origin`. */
function originMembers(origin) {
  if (!isPlainObject(origin)) return [];
  if (origin.kind === "any") return Array.isArray(origin.of) ? origin.of.filter(isPlainObject) : [];
  return [origin];
}

/** The canonical origin of `url`, or `null` when `url` is not a valid,
 * absolute URL. */
function originOf(url) {
  try {
    return new URL(url).origin;
  } catch {
    return null;
  }
}

